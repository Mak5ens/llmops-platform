"""Results of scripts/bench-autoscaling.sh: one table and one chart per scenario, from the records of each setting.

Usage: uv run --with matplotlib scripts/bench-report.py <results dir> <scenario>
Reads <results dir>/<scenario>/<setting>.csv and .json, writes <results dir>/<scenario>.md and <scenario>.png.
"""

import csv
import itertools
import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

ORDER = ["eager", "git", "frugal", "git-down30", "tuned"]


def load(directory: Path, setting: str) -> tuple[dict, list[dict]]:
    summary = json.loads((directory / f"{setting}.json").read_text())
    with (directory / f"{setting}.csv").open() as f:
        rows = [{k: float(v) for k, v in row.items()} for row in csv.DictReader(f)]
    # Time origin: the start of the k6 run rather than of the records.
    for row in rows:
        row["t"] = round(row["t"] - summary["offset"], 1)
    return summary, rows


def measures(summary: dict, rows: list[dict]) -> dict:
    ready = [r for r in rows if r["ready"] >= 1]
    peak = max(r["ready"] for r in rows)
    first = ready[0]["t"] if ready else None
    full = next(r["t"] for r in rows if r["ready"] == peak)
    busy = [r["t"] for r in rows if r["waiting"] + r["in_progress"] > 0]
    zero = next((r["t"] for r in rows if r["t"] > busy[-1] and r["replicas"] == 0), None) if busy else None
    # Each time the workers start from zero, the jobs wait for a cold start.
    starts = sum(1 for a, b in itertools.pairwise(rows) if a["replicas"] == 0 and b["replicas"] > 0)
    worker_seconds = sum(a["replicas"] * (b["t"] - a["t"]) for a, b in itertools.pairwise(rows))
    latency = summary["latency"]
    # Spike: each burst apart.
    bursts = summary["publishers"] if len(summary["publishers"]) > 1 else {}
    return {
        "jobs": f"{summary['answered']}/{summary['published']}",
        "first worker ready": f"{first:.0f} s" if first is not None else "-",
        "first job answered after": f"{summary['first'] / 1000:.1f} s",
        "1 → max workers": f"{full - first:.0f} s (→ {peak:.0f})" if first is not None else "-",
        "cold starts": str(starts),
        "latency median": f"{latency['med'] / 1000:.1f} s",
        "latency p95": f"{latency['p(95)'] / 1000:.1f} s",
        "latency max": f"{latency['max'] / 1000:.1f} s",
        **{f"latency median, {name} burst": f"{v['med'] / 1000:.1f} s" for name, v in bursts.items()},
        "queue empty → zero workers": f"{zero - busy[-1]:.0f} s" if zero is not None else "-",
        "worker-minutes": f"{worker_seconds / 60:.1f}",
    }


def main() -> None:
    results, scenario = Path(sys.argv[1]), sys.argv[2]
    directory = results / scenario
    settings = sorted((p.stem for p in directory.glob("*.json")), key=lambda s: ORDER.index(s) if s in ORDER else 99)
    runs = {s: load(directory, s) for s in settings}

    table = {s: measures(*runs[s]) for s in settings}
    lines = [
        f"# Scenario `{scenario}`",
        "",
        f"Generated by `just bench-autoscaling {scenario}` (scripts/bench-report.py). Times from the start of the k6 run.",
        "",
        "| | " + " | ".join(f"`{s}`" for s in settings) + " |",
        "| -- | " + " | ".join("--" for _ in settings) + " |",
        "| jobs per worker | " + " | ".join(str(runs[s][0]["value"]) for s in settings) + " |",
        "| zero workers after | " + " | ".join(f"{runs[s][0]['cooldown']} s" for s in settings) + " |",
        "| scale-down window | " + " | ".join(f"{runs[s][0]['window']} s" for s in settings) + " |",
    ]
    for measure in next(iter(table.values())):
        lines.append(f"| {measure} | " + " | ".join(table[s][measure] for s in settings) + " |")
    lines += ["", f"![Workers and jobs in the queue, scenario {scenario}]({scenario}.png)", ""]
    (results / f"{scenario}.md").write_text("\n".join(lines))

    fig, (workers, jobs) = plt.subplots(2, 1, figsize=(9, 6), sharex=True)
    for s in settings:
        rows = runs[s][1]
        t = [r["t"] for r in rows]
        workers.step(t, [r["ready"] for r in rows], where="post", label=s)
        jobs.plot(t, [r["waiting"] + r["in_progress"] for r in rows], label=s)
    workers.set_ylabel("ready workers")
    jobs.set_ylabel("jobs in the queue")
    jobs.set_xlabel("seconds since the start of the run")
    workers.set_title(f"Scenario {scenario}")
    for ax in (workers, jobs):
        ax.grid(alpha=0.3)
        ax.legend()
    fig.tight_layout()
    fig.savefig(results / f"{scenario}.png", dpi=90)
    print(f"Wrote {results / scenario}.md and .png")


if __name__ == "__main__":
    main()
